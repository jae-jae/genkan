import { expect, openApp, openSettings, toggleEdit, test } from '../helpers'

const source = `export const manifest = {id:"e2e-ssh",name:"SSH test",version:"1",permissions:{ssh:true},
config:[{key:"key",type:"secret",multiline:true,label:"Private key"}],widgets:[{id:"main",name:"Server"}]};
export async function widget(){return {body:[{type:"text",text:"SSH configuration test"}]}}`

test('SSH permission review and multiline secret keep/clear work without returning a saved key', async ({ page, api }) => {
  await api.call('POST', '/api/plugins', { source, enable: false })
  await openApp(page)
  await openSettings(page, 'plugins')
  const row = page.locator('[data-testid="plugin-row"][data-plugin-id="e2e-ssh"]')
  await row.getByTestId('plugin-toggle').click()
  const modal = page.getByTestId('plugin-perm-modal')
  await expect(modal.getByTestId('plugin-perm-ssh')).toContainText('SSH')
  await expect(modal.getByTestId('plugin-perm-none')).toHaveCount(0)
  await modal.getByTestId('plugin-perm-cancel').click()
  expect((await api.call('GET', '/api/plugins')).find((p: any) => p.id === 'e2e-ssh').enabled).toBe(false)
  await row.getByTestId('plugin-toggle').click()
  await modal.getByTestId('plugin-perm-allow').click()
  await row.getByTestId('plugin-config-btn').click()
  const key = page.getByTestId('plugin-cfg-key')
  await expect(key).toHaveJSProperty('tagName', 'TEXTAREA')
  const value = 'test-only-key-line-1\nline-2\nline-3'
  await key.fill(value)
  await page.getByTestId('plugin-config-save').click()
  await expect(key).toHaveAttribute('data-set', '1')
  const infos = await api.call('GET', '/api/plugins')
  const info = infos.find((p: any) => p.id === 'e2e-ssh')
  expect(info.config.key).toBe('')
  expect(info.secrets_set).toContain('key')
  expect(JSON.stringify(info)).not.toContain(value)
  await page.reload()
  await openSettings(page, 'plugins')
  await row.getByTestId('plugin-config-btn').click()
  await expect(key).toHaveValue('')
  await expect(key).toHaveAttribute('data-set', '1')
  await page.getByTestId('plugin-cfg-secret-clear-key').click()
  await page.getByTestId('plugin-config-save').click()
  await expect(key).toHaveAttribute('data-set', '0')
  const cleared = (await api.call('GET', '/api/plugins')).find((p: any) => p.id === 'e2e-ssh')
  expect(cleared.secrets_set || []).not.toContain('key')
})


test('widget picker asks before enabling SSH; cancel keeps it disabled at 375px', async ({ page, api }) => {
  await api.call('POST', '/api/plugins', { source, enable: false })
  await page.setViewportSize({ width: 375, height: 812 })
  await openApp(page)
  await toggleEdit(page)
  await page.getByTestId('widget-add').click()
  await page.getByTestId('widget-pick-e2e-ssh-main').click()
  const review = page.getByTestId('widget-ssh-permission')
  await expect(review).toBeVisible()
  await expect(review).toContainText('SSH')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByTestId('widget-ssh-cancel').click()
  expect((await api.call('GET', '/api/plugins')).find((p: any) => p.id === 'e2e-ssh').enabled).toBe(false)
  await page.getByTestId('widget-pick-e2e-ssh-main').click()
  await page.getByTestId('widget-ssh-allow').click()
  await expect(page.getByTestId('widget-form')).toBeVisible()
  expect((await api.call('GET', '/api/plugins')).find((p: any) => p.id === 'e2e-ssh').enabled).toBe(true)
})


test('new catalog SSH widget is installed disabled before permission review', async ({ page, api }) => {
  await page.route('**/api/plugins/catalog', (route) => route.fulfill({ json: [{ id: 'e2e-ssh-new', name: 'New SSH', widgets: [{ id: 'main', name: 'Server', size: 'm' }], installed: false }] }))
  await page.route('**/api/plugins', async (route) => {
    if (route.request().method() !== 'POST') return route.continue()
    const data = route.request().postDataJSON()
    expect(data.enable).toBe(false)
    const info = await api.call('POST', '/api/plugins', { source: source.replace('e2e-ssh', 'e2e-ssh-new'), enable: data.enable })
    await route.fulfill({ json: info })
  })
  await openApp(page)
  await toggleEdit(page)
  await page.getByTestId('widget-add').click()
  await page.getByTestId('widget-pick-e2e-ssh-new-main').click()
  await expect(page.getByTestId('widget-ssh-permission')).toBeVisible()
  expect((await api.call('GET', '/api/plugins')).find((p: any) => p.id === 'e2e-ssh-new').enabled).toBe(false)
  await page.getByTestId('widget-ssh-cancel').click()
  await page.getByTestId('widget-pick-e2e-ssh-new-main').click()
  await page.getByTestId('widget-ssh-allow').click()
  await expect(page.getByTestId('widget-form')).toBeVisible()
  expect((await api.call('GET', '/api/plugins')).find((p: any) => p.id === 'e2e-ssh-new').enabled).toBe(true)
})
