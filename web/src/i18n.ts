const dicts = { en, zh }

/** The browser's preferred UI language: the first of navigator.languages that is Chinese (zh*) or English (en*); anything else falls back to English. */
function browserLang(): Lang {
  const list = navigator.languages?.length ? navigator.languages : [navigator.language || '']
  for (const l of list) {
    if (/^zh\b/i.test(l)) return 'zh'
    if (/^en\b/i.test(l)) return 'en'
  }
  return 'en'
}

function readPref(): LangPref {
  const saved = lsGet('genkan.lang')
  return saved === 'zh' || saved === 'en' ? saved : 'auto' // missing / invalid -> auto
}

/** What the user picked in Settings (default: auto). */
export const langPref = signal<LangPref>(readPref())
const browser = signal<Lang>(browserLang())
/** The language the UI is actually rendered in. */
export const lang = computed<Lang>(() => (langPref.value === 'auto' ? browser.value : langPref.value))

const htmlLang = () => {
  document.documentElement.lang = lang.value === 'zh' ? 'zh-CN' : 'en'
}
effect(htmlLang)
window.addEventListener('languagechange', () => {
  browser.value = browserLang()
})

export function setLang(p: LangPref) {
  langPref.value = p
  lsSet('genkan.lang', p)
}

/** Registers strings from a lazy chunk (the plugin manager keeps its newer strings next to its code, out of the first-screen bundle). */
export const addStrings = (e: Record<string, string>, z: Record<string, string>) => (Object.assign(en, e), Object.assign(zh, z))

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang.value][key] ?? en[key] ?? key
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]))
  return s
}

/**
 * Resolves a plugin-provided LString (plain string, or { en, zh, … }) in the UI language: exact tag, base language
 * ("zh-TW" -> "zh"), "en", then the first tag alphabetically. Same chain as the server (docs/PLUGINS.md §12).
 * Reads the `lang` signal, so a component that calls it re-renders when the language changes.
 */
export function loc(v: LString | null | undefined, l: string = lang.value): string {
  if (v == null) return ''
  if (typeof v === 'string') return v
  const by: Record<string, string> = {}
  for (const k of Object.keys(v)) by[k.toLowerCase()] = v[k]
  let tag = l.toLowerCase().replace(/_/g, '-')
  while (tag) {
    if (tag in by) return by[tag]
    const i = tag.lastIndexOf('-')
    if (i < 0) break
    tag = tag.slice(0, i)
  }
  if ('en' in by) return by.en
  const first = Object.keys(v).sort()[0]
  return first === undefined ? '' : v[first]
}
